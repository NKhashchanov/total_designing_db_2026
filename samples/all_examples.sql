--   - рейтинги блюд/ресторанов НЕ пересчитываются через rating_change —
--     они либо генерируются сразу с нужным значением, либо остаются NULL
--     (если отзывов нет). См. BR-9.6.
--   - продукт добавляется INSERT-ом, а не через add_product.


