-- 10. ЗАПРЕТ на вызов других процедур/функций из insert_test_data
-- ============================================================================
-- Правило: insert_test_data НЕ ДОЛЖНА вызывать другие процедуры и функции
-- из твоей схемы (courier_salary, add_product, rating_change и т. п.).
--
-- Почему:
--   - insert_test_data — тестовый генератор. Он должен быть независим
