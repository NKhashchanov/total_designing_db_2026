-- 9. courier_pay: согласованно с заказами
-- ============================================================================
-- Правило BR-10.2: для курьера и месяца
--     amount = coefficient_used × сумма комиссий доставленных заказов
--     coefficient_used — коэффициент, действовавший в том месяце
-- Правило BR-10.5: только доставленные заказы.
-- Правило BR-10.6: уволенные курьеры получают выплату за месяц,
--                  но коэффициент на следующий месяц не обновляется.
--
-- Приём: generate_series по месяцам + агрегат по заказам.

select
    extract(year  from m)::int as y,
    extract(month from m)::int as m
from generate_series(
    date_trunc('month', current_date - interval '5 months'),
    date_trunc('month', current_date),
    interval '1 month'
) as m;

-- Применение: для каждого курьера × каждого месяца — агрегат и INSERT.
-- ⚠ Ловушка: сумма считается по order.commission, а не по total_amount.
-- ⚠ Ловушка: у курьера может не быть доставок в месяце — тогда 0, не NULL.


