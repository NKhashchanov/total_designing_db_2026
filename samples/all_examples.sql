--   - courier_salary вызывается из «ночного джоба», а не из генератора.
--   - Взаимодействие между процедурами усложняет отладку и делает
--     поведение непредсказуемым (например, если courier_salary падает —
--     падает весь insert_test_data).
--
-- Что делать вместо этого:
--   - courier_pay генерируется НАПРЯМУЮ через INSERT с расчётом суммы
